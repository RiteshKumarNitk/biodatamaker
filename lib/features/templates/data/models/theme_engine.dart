  static ThemeConfig? getById(String id) {
    try {
      return defaultTemplates.firstWhere((t) => t.id == id);
    } catch (_) {
      return null;
    }
  }

  static List<ThemeConfig> getByCategory(String category) =>
      defaultTemplates.where((t) => t.category == category).toList();

  static List<ThemeConfig> get free =>
      defaultTemplates.where((t) => !t.isPremium).toList();

  static List<ThemeConfig> get premium =>
      defaultTemplates.where((t) => t.isPremium).toList();

  static List<String> get categories =>
      defaultTemplates.map((t) => t.category).toSet().toList()..sort();

  static Map<String, List<ThemeConfig>> get groupedByCategory {
    final map = <String, List<ThemeConfig>>{};
    for (final t in defaultTemplates) {
      map.putIfAbsent(t.category, () => []).add(t);
    }
    return map;
  }
}
